export type AdCatalogFormat =
  | 'banner_adaptive'
  | 'banner_fixed'
  | 'native'
  | 'interstitial'
  | 'rewarded'
  | 'app_open'
  | 'rewarded_interstitial';

export type AdCatalogStatus =
  | 'configured'
  | 'test_mode_required'
  | 'requires_provider_setup'
  | 'not_supported';

export interface AdTestCatalogEntry {
  providerId: 'applovin' | 'admob' | 'meta' | 'inmobi' | 'unity' | 'custom_ads';
  providerName: string;
  formatKey: AdCatalogFormat;
  formatLabel: string;
  testingMethod: string;
  androidSampleId?: string | undefined;
  iosSampleId?: string | undefined;
  defaultStatus: AdCatalogStatus;
  statusDescription: string;
  documentationUrl: string;
  isUniversalId: boolean; // true if the ID is an official public sample ID from the provider
}

